#!/usr/bin/env python3
"""Build Writing posts from Markdown sources.

Each post lives in content/writing/<slug>.md: a front-matter block, then the
body in a small Markdown subset. This script renders writing/<slug>/index.html
and rewrites the generated parts of writing/index.html (between the NOTES
markers), writing/feed.xml and the post URLs in sitemap.xml. Then it runs
scripts/check.py. Commit the sources and the generated files together.

Front matter (one "key: value" per line; indent a line to continue a value):
  title    required
  date     required, YYYY-MM-DD
  summary  required, one or two sentences (index row, meta, feed)
  card     optional, share-card line (default: title)
  updated  optional, YYYY-MM-DD for the feed after a real revision
  linkedin optional, text for the LinkedIn teaser (default: summary)
  draft    optional, "true" skips the post

Markdown subset: paragraphs, "## " headings (numbered like the template),
"- " bullet lists, "> " blockquotes, [links](url), **strong**, *em*, `code`.

Run:
  python3 scripts/build_posts.py                    build every post
  python3 scripts/build_posts.py --linkedin <slug>  build, then print the teaser
Share cards: NODE_PATH=$(npm root -g) node brand/assets/generate.cjs
"""

import html
import json
import math
import os
import re
import shutil
import subprocess
import sys
from string import Template

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "content", "writing")
SITE = "https://www.boutalikakis.com"
STYLE_VERSION = "6"  # keep in step with site.css?v=N on the other pages
GENERATED = "Generated by scripts/build_posts.py"
NOTES_START, NOTES_END = "<!-- NOTES:start -->", "<!-- NOTES:end -->"
REQUIRED = ("title", "date", "summary")


# --- Sources -----------------------------------------------------------------

def parse_source(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        sys.exit(f"{path}: missing front matter between --- lines")
    meta, key = {}, None
    for line in m.group(1).splitlines():
        if line[:1].isspace() and key:
            meta[key] += " " + line.strip()
        elif ":" in line:
            key, value = line.split(":", 1)
            key = key.strip()
            meta[key] = value.strip()
    for k in REQUIRED:
        if not meta.get(k):
            sys.exit(f"{path}: front matter needs '{k}'")
    for k in ("date", "updated"):
        if k in meta and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", meta[k]):
            sys.exit(f"{path}: '{k}' must be YYYY-MM-DD")
    meta["slug"] = os.path.splitext(os.path.basename(path))[0]
    if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", meta["slug"]):
        sys.exit(f"{path}: file name must be a lowercase-hyphen slug")
    meta["body"] = m.group(2)
    return meta


def load_posts():
    posts = []
    for name in sorted(os.listdir(SRC_DIR)):
        if name.endswith(".md"):
            post = parse_source(os.path.join(SRC_DIR, name))
            if post.get("draft", "").lower() != "true":
                posts.append(post)
    # Oldest first fixes the note numbers; later lists reverse this order.
    posts.sort(key=lambda p: (p["date"], p["slug"]))
    for i, post in enumerate(posts, 1):
        post["number"] = i
    return posts


# --- Markdown subset ---------------------------------------------------------

def inline(text):
    codes = []

    def keep_code(m):
        codes.append(m.group(1))
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep_code, text)
    text = html.escape(text, quote=False)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)",
                  lambda m: f'<a href="{m.group(2).replace(chr(34), "%22")}">{m.group(1)}</a>',
                  text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    return re.sub("\x00(\\d+)\x00",
                  lambda m: f"<code>{html.escape(codes[int(m.group(1))], quote=False)}</code>",
                  text)


def render_body(markdown, slug):
    out, number = [], 0
    for block in re.split(r"\n\s*\n", markdown.strip()):
        lines = [l.rstrip() for l in block.splitlines()]
        first = lines[0]
        if first.startswith("## "):
            if len(lines) > 1:
                sys.exit(f"{slug}: put a blank line after the heading '{first}'")
            number += 1
            out.append(f"<h2><span>{number}</span><span>{inline(first[3:].strip())}</span></h2>")
        elif first.startswith("#"):
            sys.exit(f"{slug}: only '## ' headings are supported ('{first}')")
        elif first.startswith("- "):
            items = []
            for line in lines:
                if line.startswith("- "):
                    items.append(line[2:].strip())
                elif items:
                    items[-1] += " " + line.strip()
            lis = "\n".join(f"  <li>{inline(i)}</li>" for i in items)
            out.append(f"<ul>\n{lis}\n</ul>")
        elif first.startswith(">"):
            quote = " ".join(l.lstrip(">").strip() for l in lines)
            out.append(f"<blockquote><p>{inline(quote)}</p></blockquote>")
        else:
            out.append(f"<p>{inline(' '.join(l.strip() for l in lines))}</p>")
    return "\n\n".join(out)


def read_minutes(markdown):
    words = len(re.findall(r"[\w'’-]+", markdown))
    return max(1, math.ceil(words / 200))


