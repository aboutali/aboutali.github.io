AUTHOR = {
    "@type": "Person", "name": "Angelo Boutalikakis", "honorificPrefix": "Dr.",
    "url": f"{SITE}/", "image": f"{SITE}/assets/headshot.jpg",
    "jobTitle": "Engagement Manager",
    "worksFor": {"@type": "Organization", "name": "McKinsey & Company"},
    "address": {"@type": "PostalAddress", "addressLocality": "Zurich", "addressCountry": "CH"},
    "sameAs": ["https://www.linkedin.com/in/angeloboutalikakis",
               "https://scholar.google.com/citations?user=4E9KeKYAAAAJ",
               "https://github.com/aboutali"],
}


def post_url(post):
    return f"{SITE}/writing/{post['slug']}/"


def render_page(post):
    url = post_url(post)
    ld = {"@context": "https://schema.org", "@type": "BlogPosting",
          "headline": post["title"], "datePublished": post["date"]}
    if "updated" in post:
        ld["dateModified"] = post["updated"]
    ld.update({"author": AUTHOR, "mainEntityOfPage": url})
    body = render_body(post["body"], post["slug"])
    body = "\n".join(("        " + l) if l else "" for l in body.splitlines())
    esc = lambda s: html.escape(s, quote=False).replace('"', "&quot;")
    return PAGE.substitute(
        generated=GENERATED, slug=post["slug"], site=SITE, url=url,
        title=esc(post["title"]), summary=esc(post["summary"]),
        number=f"{post['number']:02d}", date=post["date"],
        minutes=read_minutes(post["body"]), body=body,
        style_version=STYLE_VERSION,
        jsonld=json.dumps(ld, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/"),
    )


# --- Index, feed, sitemap ----------------------------------------------------

def render_notes(posts):
    rows = []
    for p in reversed(posts):
        rows.append(
            f'          <a href="{p["slug"]}/">\n'
            f'            <span class="t">{html.escape(p["title"], quote=False)}</span>\n'
            f'            <span class="d">{p["date"]}</span>\n'
            f'            <span class="desc">{html.escape(p["summary"], quote=False)}</span>\n'
            f'          </a>')
    return "\n".join(rows)


def update_index(text, posts):
    start, end = text.find(NOTES_START), text.find(NOTES_END)
    if start < 0 or end < start:
        sys.exit(f"writing/index.html: missing {NOTES_START} / {NOTES_END} markers")
    return text[:start + len(NOTES_START)] + "\n" + render_notes(posts) + "\n          " + text[end:]


def render_feed(posts):
    x = lambda s: html.escape(s, quote=False)
    stamp = lambda d: f"{d}T00:00:00Z"
    newest = max((p.get("updated", p["date"]) for p in posts), default="2026-07-02")
    entries = "".join(
        "  <entry>\n"
        f"    <title>{x(p['title'])}</title>\n"
        f'    <link href="{post_url(p)}"/>\n'
        f"    <id>{post_url(p)}</id>\n"
        f"    <published>{stamp(p['date'])}</published>\n"
        f"    <updated>{stamp(p.get('updated', p['date']))}</updated>\n"
        f"    <summary>{x(p['summary'])}</summary>\n"
        "  </entry>\n"
        for p in reversed(posts))
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} from content/writing/. Edit the Markdown, not this file. -->\n"
        '<feed xmlns="http://www.w3.org/2005/Atom">\n'
        "  <title>Writing · Angelo Boutalikakis</title>\n"
        "  <subtitle>Research, publications, and notes by Angelo Boutalikakis.</subtitle>\n"
        f'  <link href="{SITE}/writing/feed.xml" rel="self"/>\n'
        f'  <link href="{SITE}/writing/"/>\n'
        f"  <id>{SITE}/writing/</id>\n"
        f"  <updated>{stamp(newest)}</updated>\n"
        f"  <author><name>Angelo Boutalikakis</name><uri>{SITE}/</uri></author>\n"
        f"{entries}"
        "</feed>\n")


def update_sitemap(text, posts):
    post_line = re.compile(r"^\s*<url><loc>" + re.escape(SITE) + r"/writing/[^<]+/</loc></url>\n", re.M)
    text = post_line.sub("", text)
    anchor = f"  <url><loc>{SITE}/writing/</loc></url>\n"
    if anchor not in text:
        sys.exit("sitemap.xml: missing the /writing/ entry")
    lines = "".join(f"  <url><loc>{post_url(p)}</loc></url>\n" for p in reversed(posts))
    return text.replace(anchor, anchor + lines, 1)


# --- Main --------------------------------------------------------------------

def write_if_changed(relpath, content):
    path = os.path.join(ROOT, relpath)
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == content:
                return
    except FileNotFoundError:
        os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"wrote {relpath}")


def read(relpath):
    with open(os.path.join(ROOT, relpath), encoding="utf-8") as f:
        return f.read()


def remove_orphans(posts):
    """Delete generated post folders whose Markdown source is gone."""
    slugs = {p["slug"] for p in posts}
    writing = os.path.join(ROOT, "writing")
    for name in sorted(os.listdir(writing)):
        page = os.path.join(writing, name, "index.html")
        if name in slugs or not os.path.isfile(page):
            continue
        with open(page, encoding="utf-8") as f:
            if GENERATED in f.read(300):
                shutil.rmtree(os.path.join(writing, name))
                print(f"removed writing/{name}/ (no source)")


def linkedin_teaser(posts, slug):
    post = next((p for p in posts if p["slug"] == slug), None)
    if not post:
        sys.exit(f"--linkedin: no published post '{slug}'")
    text = post.get("linkedin") or post["summary"]
    return f"{text}\n\n{post_url(post)}"


def main(argv):
    slug = None
    if argv[:1] == ["--linkedin"] and len(argv) == 2:
        slug = argv[1]
    elif argv:
        sys.exit(__doc__)
    posts = load_posts()
    for post in posts:
        write_if_changed(f"writing/{post['slug']}/index.html", render_page(post))
    remove_orphans(posts)
    write_if_changed("writing/index.html", update_index(read("writing/index.html"), posts))
    write_if_changed("writing/feed.xml", render_feed(posts))
    write_if_changed("sitemap.xml", update_sitemap(read("sitemap.xml"), posts))
    code = subprocess.call([sys.executable, os.path.join(ROOT, "scripts", "check.py")])
    if slug:
        print("\n--- LinkedIn post (paste as a native post) ---\n")
        print(linkedin_teaser(posts, slug))
    return code


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
